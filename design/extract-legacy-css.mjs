#!/usr/bin/env node
// Pulls the styles the rebuild keeps from today's stylesheet (legacy/src/page/styles.css) into design/mockup:
//   legacy-answer.css  what the reply renderer outputs: text, maths, tables, code, citations, sources
//   legacy-bot.css     Wind Bot's face and its moods
//   legacy-chess.css   the chess view (board, stage, cards, live chat), minus the old page's tab and layout hooks
// Each file gets every matching rule, every at-rule (@media, @container, @supports) that contains one, and the
// @keyframes they animate with. Run it again whenever legacy/src/page/styles.css changes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = fs.readFileSync(path.join(ROOT, "legacy/src/page/styles.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");

// top-level blocks, skipping braces inside strings
function blocks(text) {
  const out = []; let depth = 0, start = 0, quote = null;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote) { if (c === quote && text[i - 1] !== "\\") quote = null; continue; }
    if (c === '"' || c === "'") { quote = c; continue; }
    if (c === "{") depth++;
    else if (c === "}" && --depth === 0) { out.push(text.slice(start, i + 1).trim()); start = i + 1; }
  }
  return out;
}
const selectorOf = (b) => b.slice(0, b.indexOf("{"));
const ALL = blocks(css);
const KEYFRAMES = new Map(ALL.filter((b) => b.startsWith("@keyframes")).map((b) => [b.match(/@keyframes\s+([\w-]+)/)[1], b]));

function extract(match, skip = () => false) {
  const rules = [], at = [];
  for (const b of ALL) {
    if (b.startsWith("@keyframes") || b.startsWith("@font-face")) continue;
    if (b.startsWith("@")) {
      const inner = blocks(b.slice(b.indexOf("{") + 1, -1)).filter((r) => match(selectorOf(r)) && !skip(selectorOf(r)));
      if (inner.length) at.push(selectorOf(b).trim() + "{\n  " + inner.join("\n  ") + "\n}");
    } else if (match(selectorOf(b)) && !skip(selectorOf(b))) rules.push(b);
  }
  const text = rules.concat(at).join("\n");
  const names = new Set();
  for (const m of text.matchAll(/animation(?:-name)?\s*:\s*([^;}]+)/g)) for (const n of m[1].split(",")) { const w = n.trim().split(/\s+/).find((x) => KEYFRAMES.has(x)); if (w) names.add(w); }
  return { text: text + "\n" + [...names].map((n) => KEYFRAMES.get(n)).join("\n") + "\n", rules: rules.length, at: at.length, keyframes: names.size };
}

const FILES = {
  "legacy-answer.css": {
    note: "Reply styles: everything the reply renderer outputs.",
    match: (s) => /\.answer\b|\.math\b|\.math-block|\.m(frac|num|den|sqrt|root|rad|over|lim|big|fence|fenced|xarrow|xlab|xarr|t|i|op|int|row|table|cell|box|binom|ss|chem)\b|\.codeblock|\.code-head|\.copy-code|\.wrap-code|\.cite\b|\.callout|\.src\b|\.src-|\.sources|\.table-wrap|\.t[a-z]\b|\.ta-[rc]\b|\.nw\b/.test(s),
  },
  "legacy-bot.css": {
    note: "Wind Bot's face. Sizes are in em: the font-size of the face's box sets its size.",
    match: (s) => /\.bot\b|\.bot-|\[data-mood/.test(s),
  },
  "legacy-chess.css": {
    note: "The chess view: board, Wind Bot's stage, start and end cards, live chat. Without the old page's tab and layout hooks.",
    match: (s) => /\.cv\b|\.cv-|\.chess-view|#chessView/.test(s),
    skip: (s) => /chess-mode|\.main\.|\.tab-|\.main\s/.test(s),
  },
};
for (const [file, f] of Object.entries(FILES)) {
  const r = extract(f.match, f.skip);
  const head = `/* Generated by design/extract-legacy-css.mjs from legacy/src/page/styles.css. Do not edit: change the source and re-run.\n   ${f.note} */\n`;
  fs.writeFileSync(path.join(ROOT, "design/mockup", file), head + r.text);
  console.log(`${file.padEnd(18)} ${String(r.rules).padStart(3)} rules, ${r.at} at-rules, ${r.keyframes} keyframes`);
}
